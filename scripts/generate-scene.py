"""Render the bundled voice track and its mouth cues from local Kokoro files."""

import argparse
import json
import wave
from pathlib import Path

import numpy as np
import onnxruntime


SAMPLE_RATE = 24_000
DURATION = 15
ROOT = Path(__file__).resolve().parents[1]

# The second field is the phoneme input given to Kokoro for each line.
LINES = [
    (0.38, "Hi, I'm Mira.", "hˈaɪ, aɪm mˈɪɹə.", "neutral"),
    (2.05, "My favorite mug cracked this morning.", "maɪ fˈeɪvəɹɪt mˈʌɡ kɹˈækt ðɪs mˈɔɹnɪŋ.", "joy"),
    (5.22, "I was so mad.", "aɪ wəz sˈoʊ mˈæd.", "anger"),
    (7.05, "It was a gift.", "ɪt wəz ə ɡˈɪft.", "sadness"),
    (8.85, "I almost cried.", "aɪ ˈɔlmoʊst kɹˈaɪd.", "crying"),
    (10.96, "Ha! But hey, it makes a pretty good plant pot.", "hˈɑ! bət hˈeɪ, ɪt mˈeɪks ə pɹˈɪɾi ɡˈʊd plˈænt pˈɑt.", "laughter"),
]

MOUTH_SHAPES = {
    "closed": "bmp",
    "teeth": "fvszθð",
    "wide": "eiɪɛj",
    "open": "aɑʌæəɜh",
    "round": "oɔuʊɹ",
    "puckered": "wʃʒ",
    "tongue": "ltdnɾŋɡkɲɫʧʤ",
    "rest": ",.!?",
}
PHONEME_SHAPE = {
    phoneme: shape for shape, phonemes in MOUTH_SHAPES.items() for phoneme in phonemes
}


def synthesize_line(model, vocabulary, voice, phonemes):
    tokens = [vocabulary[phoneme] for phoneme in phonemes]
    waveform, durations = model.run(
        ["waveform", "durations"],
        {
            "input_ids": np.array([[0, *tokens, 0]], dtype=np.int64),
            "style": voice[len(tokens)],
            "speed": np.array([1], dtype=np.float32),
        },
    )
    audio = waveform[0]
    voiced = np.flatnonzero(np.abs(audio) > 0.006)
    first_sample = max(0, voiced[0] - round(0.045 * SAMPLE_RATE))
    last_sample = min(len(audio), voiced[-1] + round(0.1 * SAMPLE_RATE))
    token_frames = np.maximum(np.rint(durations[0]), 1)
    token_times = np.cumsum(token_frames)[:-2] * (len(audio) / token_frames.sum()) / SAMPLE_RATE
    return audio[first_sample:last_sample], token_times - first_sample / SAMPLE_RATE


def place_line(track, captions, cues, start, text, phonemes, line_audio, token_times):
    offset = round(start * SAMPLE_RATE)
    end_sample = offset + len(line_audio)
    if end_sample > len(track) or np.any(track[offset:end_sample]):
        raise ValueError(f"The line at {start}s overlaps another line or the end of the scene.")
    track[offset:end_sample] = line_audio
    end = end_sample / SAMPLE_RATE
    captions.append({"start": start, "end": round(end, 3), "text": text})
    for phoneme, token_time in zip(phonemes, token_times, strict=True):
        mouth = PHONEME_SHAPE.get(phoneme)
        time = round(start + max(0, float(token_time)), 3)
        if mouth and time < end and cues[-1][1] != mouth:
            if cues[-1][0] == time:
                cues[-1] = [time, mouth]
            else:
                cues.append([time, mouth])
    if cues[-1][1] != "rest":
        cues.append([round(end, 3), "rest"])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("model_directory", type=Path, help="Folder with model.onnx, config.json, and voice.bin")
    files = parser.parse_args().model_directory
    vocabulary = json.loads((files / "config.json").read_text())["vocab"]
    voice = np.fromfile(files / "voice.bin", dtype=np.float32).reshape(-1, 1, 256)
    model = onnxruntime.InferenceSession(str(files / "model.onnx"), providers=["CPUExecutionProvider"])
    track = np.zeros(DURATION * SAMPLE_RATE, dtype=np.float32)
    captions = []
    cues = [[0, "rest"]]

    for start, text, phonemes, _ in LINES:
        audio, token_times = synthesize_line(model, vocabulary, voice, phonemes)
        place_line(track, captions, cues, start, text, phonemes, audio, token_times)

    with wave.open(str(ROOT / "public" / "mira.wav"), "wb") as audio_file:
        audio_file.setparams((1, 2, SAMPLE_RATE, 0, "NONE", "not compressed"))
        audio_file.writeframes((np.clip(track, -1, 1) * 32767).astype("<i2").tobytes())

    levels = [float(np.sqrt(np.mean(samples**2))) for samples in np.array_split(track, 100)]
    waveform = [round((level / max(levels)) ** 0.55, 3) for level in levels]
    expressions = [{"start": 0, "expression": "neutral"}]
    expressions.extend({"start": start, "expression": mood} for start, _, _, mood in LINES[1:])
    expressions.extend([{"start": 3.07, "expression": "sadness"}, {"start": 14.52, "expression": "neutral"}])
    expressions.sort(key=lambda cue: cue["start"])
    scene = {
        "duration": DURATION,
        "mouthCues": cues,
        "expressions": expressions,
        "captions": captions,
        "blinks": [1.76, 4.7, 6.58, 10.25, 14.6],
    }
    (ROOT / "scene" / "cues.ts").write_text(
        "// Generated by scripts/generate-scene.py.\n"
        f"export const miraScene = {json.dumps(scene, indent=2, ensure_ascii=False)} as const;\n"
        f"export const waveform = {json.dumps(waveform)} as const;\n"
    )


if __name__ == "__main__":
    main()
